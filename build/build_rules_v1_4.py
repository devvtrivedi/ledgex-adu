#!/usr/bin/env python3
"""Builder for Implementation Rules v1.4.

Emits BOTH artifacts from one source:
  docs/LEDGEX_RULES.md   <- file of record, what I17 points at
  dist/LedgeX_Implementation_Rules_v1_4.pdf  <- presentation artifact (optional)

This builder does NOT own a copied invariant table. It imports INVARIANTS and
MAKE_TARGETS from ledgex_source.py. build_spec_v1_11.py imports the same objects.
"""
import pathlib, sys, datetime
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import ledgex_source as S
import md_convert

ROOT = pathlib.Path(__file__).resolve().parent.parent
BODY = ROOT / "text" / "LedgeX_Implementation_Rules_v1_4.txt"
OUT  = ROOT / "docs" / "LEDGEX_RULES.md"


def render_md():
    p = []
    p.append(f"# LedgeX / ADU.X — Implementation Rules v{S.RULES_VERSION}")
    p.append("")
    p.append(f"**{S.PHASE} — {S.REVISION_DATE} — current operational control.**")
    p.append("")
    p.append("> **This file is the record.** Generated by `build/build_rules_v1_4.py` "
             "from `build/ledgex_source.py`. Do not hand-edit. The PDF of the same "
             "name is a presentation artifact rendered from this same source; where "
             "they differ, regenerate — never patch one to match the other. (I17)")
    p.append("")
    p.append("## Authority order")
    p.append("")
    p.append(S.md_table(
        ["Rank", "Document", "Role"],
        [("1", f"Engineering Reference Spec v{S.SPEC_VERSION}", "Machine-executed build contract."),
         ("2", f"Implementation Rules v{S.RULES_VERSION}", "Operational restatement of the Spec."),
         ("3", "Business Plan 2.1.4", "Commercial master."),
         ("4", "Municipal Data & API Audit v1.1", "Municipal evidence and rights."),
         ("5", "San José Data Source Checklist v1.2", "Source planning.")]))
    p.append("")
    p.append("## 1. Invariants — I1 to I20")
    p.append("")
    p.append("Evidence, rights and immutability gates apply before any product or "
             "measurement use. Each invariant has a CI check. A pull request that "
             "violates one does not merge.")
    p.append("")
    p.append(S.invariant_table_md())
    p.append("")
    p.append("## 2. Six make targets")
    p.append("")
    p.append("A target name without execution scope and a pass condition is not a "
             "definition of done.")
    p.append("")
    p.append(S.make_target_table_md())
    p.append("")
    p.append("## 3. A-1 scope")
    p.append("")
    p.append(S.md_table(["Item", "Title", "Scope"], S.A1_SCOPE, bold_first=True))
    p.append("")
    p.append("> **ONE INVARIANT SOURCE**")
    p.append(">")
    p.append("> `build/ledgex_source.py` owns `INVARIANTS` and `MAKE_TARGETS`. "
             "`build_spec_v1_11.py` imports the same objects. A change that produces "
             "different invariant text in the two artifacts fails document QA "
             "(`python build/qa_check.py`).")
    p.append("")
    p.append("---")
    p.append("")
    p.append("## Appendix — full operational body")
    p.append("")
    p.append("Converted verbatim from the v1.4 source document. Section numbering "
             "follows the original.")
    p.append("")
    if BODY.exists():
        # "2 / Six make targets" cut the corrupted I1-I20 prose block but kept
        # this section's own prose restatement of the make-targets table,
        # which duplicates the canonical table rendered above (§0.2/I17: one
        # invariant source). The next real section boundary is "3 / A-1.1
        # licence gate and document repair" — the literal "3. A-1 scope" this
        # anchor was requested as does not appear anywhere in the source text,
        # so it would have been a silent no-op, same failure mode as the
        # earlier "Section 2" anchor. This does drop one sentence of unique
        # closing prose from the make-targets section ("All six targets run
        # locally and in CI with zero required skips...") along with the
        # duplicate table — accepted; that line isn't stated anywhere else.
        p.append(md_convert.convert(BODY.read_text(encoding="utf-8"),
                                    drop_before="3 / A-1.1 licence gate and document repair"))
    p.append("")
    p.append("---")
    p.append("")
    p.append(f"*Generated {datetime.date.today().isoformat()} by "
             f"`build/build_rules_v1_4.py`. Source of record: `build/ledgex_source.py`.*")
    return "\n".join(p)


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render_md(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
