#!/usr/bin/env python3
"""Builder for the Engineering Reference Spec (version: ledgex_source.SPEC_VERSION).

Emits BOTH artifacts from one source:
  docs/LEDGEX_SPEC.md  <- file of record, what I17 points at
  dist/LedgeX_Engineering_Reference_Spec_v<SPEC_VERSION>.pdf <- presentation artifact (optional)

Imports INVARIANTS and MAKE_TARGETS from ledgex_source.py. Spec sec 0.2:
"Neither artifact is generated from a copied invariant table."

This file's own name carries no version (unlike its 1.7-1.16 predecessors,
build_spec_v1_N.py): the version lives in exactly one place,
ledgex_source.SPEC_VERSION, and every reference to it below — including the
BODY path — is derived from that, not hand-swept on every bump.
"""
import pathlib, sys, datetime
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import ledgex_source as S
import md_convert

ROOT = pathlib.Path(__file__).resolve().parent.parent
# Derived, not hardcoded: a bump that changes SPEC_VERSION but forgets to
# rename the .txt source (the manual half of a version bump that remains,
# since the text IS a versioned document -- see CLAUDE.md) fails loudly
# below via BODY.exists(), instead of silently building an appendix-less
# spec from a BODY path that quietly kept pointing at stale text.
BODY = ROOT / "text" / f"LedgeX_Engineering_Reference_Spec_v{S.SPEC_VERSION.replace('.', '_')}.txt"
OUT  = ROOT / "docs" / "LEDGEX_SPEC.md"

# The source text cross-references both builders by name in prose (§0.2's
# "One invariant source" paragraph). {{BUILD_SPEC_PY}} derives from this
# script's own filename -- pathlib.Path(__file__).name, not a literal --
# so a future rename can't leave a stale name behind the way
# build_spec_v1_8.py did (found in both .txt sources, discovered on the
# v1.16->de-versioning pass; neither instance had reached the generated
# docs yet, but both were wrong). BUILD_RULES_PY names a stable sibling
# file this script doesn't own; a literal is fine here since it no longer
# changes on every version bump, but the token still means one string to
# fix, not a grep-and-sweep, if it's ever renamed again.
BUILD_SPEC_PY = pathlib.Path(__file__).name
BUILD_RULES_PY = "build_rules.py"

# SECTION_INDEX (§, governs, use-when) moved to ledgex_source.py -- shared
# with build_spec_index.py now, same "one source" shape as INVARIANTS/
# MAKE_TARGETS. See its own comment there: row 8 no longer exists (never
# corresponded to a real section of this document); row 6 is carried with
# an honest governs string even though it has no top-level heading of its
# own -- build_spec_index.py is what actually verifies its subsections
# still exist, since this table just renders the three columns as given.


def render_md():
    p = []
    p.append(f"# LedgeX / ADU.X — Engineering Reference Spec v{S.SPEC_VERSION}")
    p.append("")
    p.append(f"**Current controlling engineering contract — {S.PHASE}, "
             f"incorporated City of San José — {S.REVISION_DATE}.**")
    p.append("")
    p.append("> **This file is the contract and the file of record.** Generated by "
             "`build/build_spec.py` from `build/ledgex_source.py`. Do not "
             "hand-edit. If an instruction in a chat message conflicts with this "
             "file, this file wins until amended by an explicit commit. Amendments "
             "require a version bump and a row in §12. (I17)")
    p.append("")
    p.append("## 0. How to use this file")
    p.append("")
    p.append("**For Claude Code / any coding agent.** This file lives at "
             "`docs/LEDGEX_SPEC.md`. Reference it from `CLAUDE.md`:")
    p.append("")
    p.append("```md\n# CLAUDE.md\nRead `docs/LEDGEX_SPEC.md` §1 (Invariants) in full, "
             "every session. It is not\nthe part to skip. For everything else, start at "
             "`docs/SPEC_INDEX.md` and read in\nfull every section your change touches. "
             "If you cannot tell from the index which\nsections a change touches, say so "
             "and stop -- do not default to reading the\nwhole file.\nNever write "
             "jurisdiction-specific logic into `core/`. See §1.I1 and §6.2.\n```")
    p.append("")
    p.append("**Reading order for a new task:** §1 invariants → §2 layout → the "
             "section for your layer (§3 schema, §4 API, §5 runtime) → §6.1 for the "
             "matching task shape → §6.3 definition of done.")
    p.append("")
    p.append("### Section index")
    p.append("")
    p.append(S.md_table(["§", "Section", "Use when"], S.SECTION_INDEX, bold_first=True))
    p.append("")
    p.append("### Authority order")
    p.append("")
    p.append(S.md_table(
        ["Rank", "Document", "Role"],
        [("1", f"This Spec v{S.SPEC_VERSION}", "Machine-executed build contract."),
         ("2", f"Implementation Rules v{S.RULES_VERSION}", "Operational restatement."),
         ("3", "Business Plan 2.1.4", "Commercial master."),
         ("4", "Municipal Data & API Audit v1.1", "Municipal evidence and rights."),
         ("5", "San José Data Source Checklist v1.2", "Source planning.")]))
    p.append("")
    p.append("### 0.2 One invariant source")
    p.append("")
    p.append("`build/ledgex_source.py` owns `INVARIANTS` and `MAKE_TARGETS`. "
             "`build_spec.py` and `build_rules.py` both import those "
             "objects. Neither the markdown nor the PDF is generated from a copied "
             "invariant table. Document QA fails if any invariant body or enforcement "
             "cell differs between artifacts.")
    p.append("")
    p.append("> **NO CLAIM OF APPLICATION EXECUTION**")
    p.append(">")
    p.append("> This Spec defines schema, jobs and tests. It does not claim "
             "migrations or repository tests have run. The A-1 merge checks are "
             "mandatory before application-code merge and remain pending until "
             "recorded by CI evidence.")
    p.append("")
    p.append("## 1. Invariants — I1 to I20")
    p.append("")
    p.append("I1–I10 preserve evidence, rights, refusal and geometry-degraded Base "
             "Core behavior. I11–I20 govern citations, automation, commerce "
             "separation, review evidence and A-1 measurement/provider gates. "
             "**Each has a CI check. A pull request that violates one does not merge.**")
    p.append("")
    p.append(S.invariant_table_md())
    p.append("")
    p.append("### 1.1 Why the licence gate covers internal facts")
    p.append("")
    p.append("A fact used to resolve jurisdiction participates in composition even if "
             "it is not rendered. Letting unknown-rights `city_limits` pass internally "
             "would authorize a conclusion the licence does not support. I6 therefore "
             "gates every *touched* fact, not only every rendered fact.")
    p.append("")
    p.append("### 1.2 Six make targets")
    p.append("")
    p.append(S.make_target_table_md())
    p.append("")
    p.append("## 15. Architecture Addendum A-1")
    p.append("")
    p.append(S.md_table(["Item", "Title", "Scope"], S.A1_SCOPE, bold_first=True))
    p.append("")
    p.append("> **STRUCTURAL DRIFT PREVENTION**")
    p.append(">")
    p.append("> Both builders import the invariant and make-target objects from "
             "`build/ledgex_source.py`. A future revision changes the source object "
             "once and regenerates both artifacts; copying is prohibited.")
    p.append("")
    p.append("---")
    p.append("")
    p.append("## Appendix — full technical body")
    p.append("")
    p.append(f"Converted verbatim from the v{S.SPEC_VERSION} source document: schema DDL, API "
             "contracts, runtime workflow, San José source list, field vocabulary, "
             "refusal codes, measurement, environment, change record, subscription "
             "commerce and launch dependencies. Section numbering follows the original.")
    p.append("")
    if not BODY.exists():
        raise FileNotFoundError(
            f"{BODY} not found. SPEC_VERSION is {S.SPEC_VERSION!r} but no "
            f"text/LedgeX_Engineering_Reference_Spec_v{S.SPEC_VERSION.replace('.', '_')}.txt "
            "exists -- rename the previous version's .txt (git mv, so history "
            "follows) as part of this version bump. Failing loudly here instead "
            "of silently omitting the appendix.")
    # Start at Section 2. Section 1 is rendered above from ledgex_source.py
    # and must not appear twice — a second copy would be a copied invariant
    # table, which sec 0.2 prohibits.
    body_text = (BODY.read_text(encoding="utf-8")
                 .replace("{{BUILD_SPEC_PY}}", BUILD_SPEC_PY)
                 .replace("{{BUILD_RULES_PY}}", BUILD_RULES_PY)
                 .replace("{{SECTION_6_3_PROVENANCE}}", S.SECTION_6_3_PROVENANCE))
    p.append(md_convert.convert(body_text, drop_before="Section 2"))
    p.append("")
    p.append("---")
    p.append("")
    p.append(f"*Generated {datetime.date.today().isoformat()} by "
             f"`build/build_spec.py`. Source of record: `build/ledgex_source.py`.*")
    return "\n".join(p)


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render_md(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
