#!/usr/bin/env python3
"""Builder for docs/SPEC_INDEX.md -- a generated table of contents for
docs/LEDGEX_SPEC.md, so a session can look up which section covers what
without paying that file's full cost (~209 KB / ~52k tokens) just to find
a starting point.

Emits from build/ledgex_source.py's SECTION_INDEX -- the same "one source,
two artifacts" shape sec 0.2 already establishes for INVARIANTS/
MAKE_TARGETS. build_spec.py's own "Section index" table (rendered inside
the Spec itself, §0) now reads S.SECTION_INDEX too, so there is exactly
one place this data is declared, not two independently hand-maintained
tables that can drift from each other and from the document they
describe -- which is exactly what happened before this file existed (see
the SECTION_INDEX comment in ledgex_source.py: two of its former rows
named sections that were not actually present in the generated document,
undetected because nothing had ever cross-checked the index against real
headings).

That cross-check is this file's actual job, not just formatting: every
SECTION_INDEX entry's number must correspond to an ACTUAL "## N. Title"
heading produced by build_spec.render_md() -- called directly, in memory,
never read off disk, so this can never validate against a stale spec.
An entry naming a section that isn't really there raises here instead of
silently emitting a link to nowhere.
"""
import datetime
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import ledgex_source as S  # noqa: E402
import build_spec  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "SPEC_INDEX.md"

HEADING_RE = re.compile(r"^## (\d+)\. (.+?)\s*$", re.M)


def _slugify(number, title):
    """GitHub-flavored-markdown heading anchor: lowercase, drop anything
    that isn't a word char/space/hyphen, collapse whitespace to hyphens.
    This is the same algorithm GitHub (and every renderer this repo's own
    website build assumes) uses to turn a heading into its #anchor."""
    text = f"{number}. {title}".lower()
    text = re.sub(r"[^\w\s-]", "", text)
    text = re.sub(r"\s+", "-", text.strip())
    return text


def render_md():
    spec_text = build_spec.render_md()
    real_headings = {m.group(1): m.group(2) for m in HEADING_RE.finditer(spec_text)}

    rows = []
    missing = []
    for number, governs, use_when in S.SECTION_INDEX:
        title = real_headings.get(number)
        if title is None:
            missing.append(number)
            continue
        anchor = _slugify(number, title)
        location = f"[§{number}](LEDGEX_SPEC.md#{anchor})"
        rows.append((number, title, use_when, location))

    if missing:
        raise ValueError(
            "SECTION_INDEX (build/ledgex_source.py) names section(s) "
            f"{missing} but build_spec.render_md() has no matching "
            "'## N. Title' heading for them right now -- SECTION_INDEX is "
            "stale, or the spec build is broken. Fix the data at its "
            "source (ledgex_source.py) or the generator, not this output."
        )

    p = []
    p.append("# Spec index")
    p.append("")
    p.append(f"**Generated by `build/build_spec_index.py` from "
              f"`build/ledgex_source.py`'s `SECTION_INDEX` -- do not "
              f"hand-edit.** One row per top-level section of "
              f"`docs/LEDGEX_SPEC.md` (v{S.SPEC_VERSION}): what it covers, "
              f"when to read it, and a direct link to the heading.")
    p.append("")
    p.append(S.md_table(["§", "Title", "Governs", "Location"], rows, bold_first=True))
    p.append("")
    p.append(f"*Generated {datetime.date.today().isoformat()} by "
              f"`build/build_spec_index.py`. Source of record: "
              f"`build/ledgex_source.py`.*")
    return "\n".join(p)


if __name__ == "__main__":
    OUT.write_text(render_md(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
