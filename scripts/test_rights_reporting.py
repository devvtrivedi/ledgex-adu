failures = []


def check(label, condition, detail=""):
    status = "PASS" if condition else "FAIL"
    print(f"[{status}] {label}" + (f" -- {detail}" if detail and not condition else ""))
    if not condition:
        failures.append(label)


# ---------------------------------------------------------------------------
# 1a. derive_rights_position -- the full 45-row truth table
# ---------------------------------------------------------------------------
# permission_state (0001): 'allowed', 'prohibited', 'unknown'.
# use_restriction (0001):  'open', 'attribution', 'noncommercial',
#                          'no_resale', 'unknown'.
PERMISSION_STATES = ("allowed", "prohibited", "unknown")
RESTRICTIONS = ("open", "attribution", "noncommercial", "no_resale", "unknown")

RIGHTS_POSITION_TABLE = {}
for cu in PERMISSION_STATES:
    for rd in PERMISSION_STATES:
        for rs in RESTRICTIONS:
            if cu == "unknown" or rd == "unknown" or rs == "unknown":
                expected = "unknown"
            elif cu == "prohibited" or rd == "prohibited":
                expected = "prohibits_use"
            elif rs == "open":
                expected = "permits_use"
            else:
                expected = "permits_with_conditions"
            RIGHTS_POSITION_TABLE[(cu, rd, rs)] = expected

# Spot-check the table itself against the two real seeded licences and the
# one real prohibited example this repo declares (sanborn_asserted,
# jurisdictions/ca_san_jose/sources.yaml/licences.yaml -- not seeded as a
# real licence row, but its combination is a real, named one) -- catches a
# transcription error in the 45-row generation above before trusting it to
# grade api/main.py.
assert RIGHTS_POSITION_TABLE[("allowed", "allowed", "open")] == "permits_use"
assert RIGHTS_POSITION_TABLE[("allowed", "allowed", "attribution")] == "permits_with_conditions"
assert RIGHTS_POSITION_TABLE[("prohibited", "prohibited", "noncommercial")] == "prohibits_use"
assert RIGHTS_POSITION_TABLE[("unknown", "unknown", "unknown")] == "unknown"
assert len(RIGHTS_POSITION_TABLE) == 45


def test_rights_position_matrix():
    for (cu, rd, rs), expected in sorted(RIGHTS_POSITION_TABLE.items()):
        got = viewer.derive_rights_position(cu, rd, rs)
        check(
            f"derive_rights_position(commercial_use={cu!r}, redistribution={rd!r}, "
            f"restriction={rs!r}) == {expected!r}",
            got == expected,
            f"got {got!r}",
        )
    # Amendment 1's own forbidden values -- never emitted for any input.
    forbidden = {"allowed", "restricted"}
    emitted = set(RIGHTS_POSITION_TABLE.values())
    check(
        "no forbidden rights_position value ('allowed', 'restricted') is ever emitted",
        emitted.isdisjoint(forbidden),
        f"emitted values: {sorted(emitted)}",
    )


# ---------------------------------------------------------------------------
# 1b. derive_diligence -- the three-state table (Amendment 2)
# ---------------------------------------------------------------------------
DILIGENCE_TABLE = {
    # (cleared_by, evidence_uri) -> expected
    (None, None): "written_confirmation_pending",
    (None, "s3://evidence/whatever"): "written_confirmation_pending",  # cleared_by NULL wins
    ("someone", None): "cleared_unevidenced",
    ("someone", "s3://evidence/whatever"): "cleared",
}


def test_diligence_matrix():
    for (cleared_by, evidence_uri), expected in DILIGENCE_TABLE.items():
        got = viewer.derive_diligence(cleared_by, evidence_uri)
        check(
            f"derive_diligence(cleared_by={cleared_by!r}, evidence_uri={evidence_uri!r}) == {expected!r}",
            got == expected,
            f"got {got!r}",
        )
    # Amendment 2's whole point: a cleared_by with no evidence_uri must NOT
    # read as plain "cleared" -- the exact shape of the closed CLAUDE.md
    # contamination incident (fabricated cleared_by='test', no evidence).
    check(
        "cleared_by set + evidence_uri NULL is 'cleared_unevidenced', never plain 'cleared'",
        viewer.derive_diligence("someone", None) == "cleared_unevidenced",
    )


# ---------------------------------------------------------------------------
# 2a. core.rights.evaluate_rights_gate -- untouched, proven with a fake
#     cursor rather than asserted by inspection. Also covers section 6's
#     "a licence with no licence_channel row at all still reports as
#     blocked" -- default-deny is evaluate_rights_gate's own behavior,
#     reporting cannot see or change it.
# ---------------------------------------------------------------------------
class _FakeCursor:
    """Returns zero licence_channel rows for every licence_id, simulating a
    real licence that has a `licence` row (satisfying fact.licence_id's FK)
    but literally no licence_channel row for any channel -- the case
    default-deny (0002) exists for. No real database involved; this is
    exactly what evaluate_rights_gate's own SELECT would see against such a
    licence."""

    def execute(self, query, params):
        self._params = params

    def fetchall(self):
        return []  # zero licence_channel rows found, for any licence_id queried


def test_default_deny_unaffected_by_reporting():
    touched = [
        ("fact-1", "some.field", "licence_with_no_channel_rows", "some value"),
    ]
    allowed_by_licence, blocked_by_licence = evaluate_rights_gate(
        _FakeCursor(), touched, "api"
    )
    check(
        "a licence with zero licence_channel rows is absent from allowed_by_licence "
        "(not merely False) -- .get(id, False) is still the only safe read",
        "licence_with_no_channel_rows" not in allowed_by_licence,
    )
    check(
        "that licence's touched field is blocked (default-deny), unchanged by this pass",
        blocked_by_licence.get("licence_with_no_channel_rows") == ["some.field"],
        f"got {blocked_by_licence}",
    )


