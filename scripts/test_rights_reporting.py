def test_model_training_rationale_distinct_from_the_other_five():
    """P52 prompt section 3, THE TRAP: rights_position/diligence are
    licence-level; the reason a specific CHANNEL is blocked is
    channel-level, and licence_channel.rationale must stay authoritative
    per channel -- never flattened into one licence-level string. If a
    future refactor collapses per-channel rationale into a single
    licence-level label, cc_by_4_0's model_training row (denied for its
    OWN, independent reason -- 0032, C9) would silently start reporting
    the same reason as free_snapshot/paid_property_file/api/bulk_export/
    analytics. This test exists to catch exactly that regression, not to
    exercise happy-path plumbing."""
    conn = get_db()
    try:
        rows = viewer.get_rights(conn)["data"]
    finally:
        conn.close()

    cc_by_4_0_rows = {r["channel"]: r["rationale"] for r in rows if r["licence_id"] == "cc_by_4_0"}
    check(
        "cc_by_4_0 has all six channels present in GET /v1/rights",
        set(cc_by_4_0_rows) == {
            "free_snapshot", "paid_property_file", "api", "bulk_export",
            "analytics", "model_training",
        },
        f"got channels: {sorted(cc_by_4_0_rows)}",
    )
    other_five = {ch: r for ch, r in cc_by_4_0_rows.items() if ch != "model_training"}
    check(
        "the other five channels share one identical rationale string",
        len(set(other_five.values())) == 1,
        f"got {len(set(other_five.values()))} distinct rationale strings among the five",
    )
    check(
        "model_training's rationale is NOT the same string as the other five",
        cc_by_4_0_rows.get("model_training") not in set(other_five.values()),
        f"model_training rationale: {cc_by_4_0_rows.get('model_training')!r}",
    )
    check(
        "model_training's rationale explicitly names model-training use, not generic sign-off",
        "model-training" in (cc_by_4_0_rows.get("model_training") or ""),
        f"got: {cc_by_4_0_rows.get('model_training')!r}",
    )
    # rights_position/diligence, being licence-level, ARE the same across
    # all six rows -- confirming they are context, not a per-channel
    # decision, the distinction section 3 requires the viewer to preserve.
    rights_positions = {r["rights_position"] for r in rows if r["licence_id"] == "cc_by_4_0"}
    diligences = {r["diligence"] for r in rows if r["licence_id"] == "cc_by_4_0"}
    check(
        "rights_position is identical across all six of cc_by_4_0's channel rows (licence-level)",
        len(rights_positions) == 1,
        f"got {rights_positions}",
    )
    check(
        "diligence is identical across all six of cc_by_4_0's channel rows (licence-level)",
        len(diligences) == 1,
        f"got {diligences}",
    )


def test_no_fabricated_evidence_in_either_response():
    """cc0/cc_by_4_0 both carry evidence_uri IS NULL in every reachable
    seeded database (Phase 1 section 3, confirmed again here live) --
    neither GET /v1/rights nor GET /v1/parcels/{id}/facts may report
    diligence='cleared' for either, since 'cleared' asserts a retained
    evidence artifact exists."""
    conn = get_db()
    try:
        rights_rows = viewer.get_rights(conn)["data"]
    finally:
        conn.close()

    for licence_id in ("cc0", "cc_by_4_0"):
        rows = [r for r in rights_rows if r["licence_id"] == licence_id]
        check(
            f"{licence_id}: evidence_uri is NULL in the live database (not this test's assumption)",
            all(r["evidence_uri"] is None for r in rows),
            f"got evidence_uri values: {[r['evidence_uri'] for r in rows]}",
        )
        check(
            f"{licence_id}: diligence is never 'cleared' while evidence_uri is NULL",
            all(r["diligence"] != "cleared" for r in rows),
            f"got diligence values: {[r['diligence'] for r in rows]}",
        )


