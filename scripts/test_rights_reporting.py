#!/usr/bin/env python3
"""P52 -- proof that the rights-vs-diligence REPORTING split (api/main.py's
derive_rights_position/derive_diligence, GET /v1/rights, and
GET /v1/parcels/{id}/facts' omitted_for_rights) does what Phase 1's plan
and Phase 2's four amendments require, and nothing more.

Two kinds of check here, mirroring scripts/test_viewer_rights_gate.py's own
split between "call the pure function" and "call the real route against a
real database":

  1. PURE, no database: the full derive_rights_position truth table (every
     commercial_use x redistribution x restriction combination -- all 45,
     not a sample) and the three-state derive_diligence table. Each
     expected value below is hand-written independently of api/main.py's
     implementation, transcribed directly from Amendment 1/2's own
     precedence rules -- not generated by calling the function under test
     and asserting it agrees with itself.

  2. DATABASE-BACKED, against real seeded data (db/seeds/day4_sources.sql):
     the model_training-rationale-distinctness requirement (P52 prompt
     section 3), the no-fabrication requirement (section 6), and a
     default-deny-is-reporting-blind check directly against
     core.rights.evaluate_rights_gate using a fake cursor -- proving this
     pass did not touch that function's behavior, not merely asserting it
     by inspection.

Run: DATABASE_URL=... .venv-api/bin/python3 scripts/test_rights_reporting.py
(same DATABASE_URL contract as scripts/test_viewer_rights_gate.py -- this
script does not seed anything itself and does not require the P42 fixture;
it reads cc0/cc_by_4_0 directly, which db/seeds/day4_sources.sql already
provides on any database it has been applied to.)

Read-only. Writes nothing.
"""
